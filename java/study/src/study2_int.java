public class study2_int {
    public static void main(String[] args) {
        int age=20;//整型
        age=19;//变量可以改变
        double height=170.1;//浮点型
        boolean student=true;//布尔类型
        String name ="leihongyuan";//字符串类型
        System.out.println("名字："+name);//+号表示和变量的拼接
        System.out.println("年龄："+age);
        System.out.println("身高："+height);
        System.out.println("是否为学生："+student);

    }
}
